import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { initStore, saveItem, saveSources } from '../src/storage.js';
import { startDashboard } from '../src/dashboard.js';
import { createManualItem } from '../src/adapters/manual.js';
import { makeSource } from '../src/models.js';
const root = await mkdtemp(join(tmpdir(), 'intake-source-filter-'));
let browser, dashboard;
try {
 await initStore(root);
 const personal = makeSource('manual', { id: 'personal', name: 'Personal' });
 const business = makeSource('manual', { id: 'business', name: 'Business' });
 await saveSources(root, [personal, business]);
 const item = await createManualItem(root, personal, { title: 'Personal archived', body: 'Fixture' });
 item.status = 'resolved'; await saveItem(root, item);
 for (let i=0;i<22;i++) await saveItem(root, await createManualItem(root,business,{title:'Business item '+i,body:'Fixture'}));
 dashboard = await startDashboard(root,{port:0,token:'source-filter-test-token'});
 browser = await chromium.launch({headless:true,...(process.env.INTAKE_TEST_CHROME ? {channel:'chrome'} : {})});
 const page = await browser.newPage();page.setDefaultTimeout(10000);const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(dashboard.url);
 await Promise.all([page.waitForResponse(r=>r.url().includes('/api/items?') && r.url().includes('view=all')),page.locator('#queues').getByRole('button',{name:/^All items 23$/}).click()]);
 await page.getByRole('button',{name:'View more',exact:true}).waitFor();
 await page.locator('#sourceFilter').selectOption('personal');
 await page.locator('.item-title').filter({hasText:/^Personal archived$/}).waitFor();
 assert.equal(await page.locator('.item-title').filter({hasText:/^Business item/}).count(),0);
 const response = page.waitForResponse(r=>r.url().includes('/api/items?')&&r.url().includes('source=business'));
 await page.locator('#sourceFilter').selectOption('business');await response;
 await page.getByRole('button',{name:'View more',exact:true}).waitFor();
 assert.equal(await page.locator('.item-title').filter({hasText:/^Personal archived$/}).count(),0);
 await page.getByRole('button',{name:'View more',exact:true}).click();
 await page.waitForFunction(()=>document.querySelectorAll('.item-title').length===22);
 assert.equal(await page.locator('.item-title').filter({hasText:/^Business item/}).count(),22);
 await page.locator('#sourceFilter').selectOption('');
 await page.getByRole('button',{name:'View more',exact:true}).waitFor();
 await page.getByRole('button',{name:'View more',exact:true}).click();
 await page.locator('.item-title').filter({hasText:/^Personal archived$/}).waitFor();
 assert.deepEqual(errors,[]);console.log('PASS: all items includes resolved; source isolation, pagination and clearing source filter work.');
} finally {if(browser)await browser.close();if(dashboard)await new Promise(resolve=>dashboard.server.close(resolve));await rm(root,{recursive:true,force:true});}
