import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { initStore, saveSources, saveItem, saveAction } from '../src/storage.js';
import { makeSource, makeItem, makeAction } from '../src/models.js';
import { startDashboard } from '../src/dashboard.js';
const root = await mkdtemp(join(tmpdir(),'intake-browser-mail-'));
let browser, dashboard;
try {
 await initStore(root);
 await saveSources(root,[makeSource('email',{id:'mail',name:'Test account'})]);
 const item = makeItem({source_id:'mail',source_type:'email',title:'Campaign preview',body:'Original body',author_email:'test@example.com',metadata:{outreach:{campaign_id:'fixture'}}});
 const action = makeAction({intake_item_id:item.id,source_id:'mail',type:'draft_response',status:'executed',body:'Original body',metadata:{subject:'Original subject',outreach:{campaign_id:'fixture'}}});
 await saveItem(root,{...item,selected_action:action.id}); await saveAction(root,action);
 dashboard = await startDashboard(root,{port:0,token:'browser-test'});
 browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(dashboard.url);
 await page.getByRole('button',{name:'Campaign preview'}).click();
 await page.getByRole('heading',{name:'Campaign draft',exact:true}).waitFor();
 assert.equal(await page.locator('#mailBody').inputValue(),'Original body');
 await page.locator('#mailBody').fill('Proposed revised copy');
 await page.getByRole('button',{name:'Save for review',exact:true}).click();
 await page.getByText('Proposal saved for campaign copy review',{exact:true}).waitFor();
 await page.reload();
 await page.getByRole('button',{name:'Campaign preview'}).click();
 assert.equal(await page.locator('#mailBody').inputValue(),'Proposed revised copy');
 await page.getByRole('button',{name:'Compose email',exact:true}).click();
 await page.locator('#mailTo').fill('recipient@example.com');
 await page.locator('#mailSubject').fill('A new message');
 await page.locator('#mailBody').fill('A test email that will not be sent.');
 await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await page.getByText('Draft saved',{exact:true}).waitFor();
 assert.equal(await page.getByRole('button',{name:'Send email',exact:true}).isEnabled(),true);
 await page.locator('#mailBody').fill('Unsaved correction');
 assert.equal(await page.getByRole('button',{name:'Send email',exact:true}).isEnabled(),false);
 await page.getByRole('button',{name:'Save draft',exact:true}).click();
 await page.getByText('Draft saved',{exact:true}).waitFor();
 await page.screenshot({path:"/tmp/intake-mail-editor-desktop.png",fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth),true);
 assert.deepEqual(errors,[]);
 console.log('PASS email editor: campaign proposal persistence, compose/save, unsaved send guard, mobile layout; no email sent');
} finally {await browser?.close();if(dashboard) await new Promise(r=>dashboard.server.close(r));await rm(root,{recursive:true,force:true});}
